/* Индекс базы ID во внешней флеш: 4096 корзин по 32 номера ячейки.
   Корзина выбирается по ID, поиск карты - одно чтение 64 байт и сверка
   одной-двух ячеек вместо перебора всей базы. При изменении таблицы индекс
   сбрасывается и пересобирается в фоне. Признак верности индекса - сумма XOR
   хешей (номер, ID) всех ячеек: при старте она сверяется с суммой, посчитанной
   по самой базе; расхождение (обрыв питания, запись старой прошивкой) -
   индекс пересобирается в фоне, а поиск пока идёт перебором. */
#ifndef IDINDEX_H
#define IDINDEX_H
#ifdef IDINDEX_HOST_TEST
#include <stdint.h>
#include <stdbool.h>
#else
#include "includes.h"
#endif

#define IDINDEX_CELL 32u /* размер ячейки базы ID: номер (2 байта), ID (10 байт), ... */

/* Хеш ячейки для суммы верности; пустая ячейка не учитывается. */
uint32_t idindex_hash(uint16_t index, const uint8_t *id);
/* Итог полного прохода по базе: сумма хешей непустых ячеек.
   Первый вызов после старта сверяет её с отметкой индекса. */
void idindex_scanned(uint32_t sum, uint16_t cells_end);
/* 1 - найден (ячейка в cell), 0 - нет, -1 - индекс не готов, искать перебором. */
int8_t idindex_find(uint32_t base, const uint8_t *id, uint8_t *cell);
/* Фоновая пересборка, по одному короткому шагу за вызов. */
void idindex_poll(uint32_t base);
/* Текущая операция W25; suspend ждёт её проверки, сохраняя источник. */
bool idindex_runtime_active(void);
void idindex_runtime_suspend(void);

#endif
