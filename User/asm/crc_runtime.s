; Продолжить CRC16 по count байтам FF с переданного начального значения.
crc16_ffInit:
        PUSH {R4-R8,LR}
        CFI R4 Frame(CFA,-24)
        CFI R5 Frame(CFA,-20)
        CFI R6 Frame(CFA,-16)
        CFI R7 Frame(CFA,-12)
        CFI R8 Frame(CFA,-8)
        CFI R14 Frame(CFA,-4)
        CFI CFA R13+24
        MOV R4,R0
        MOV R5,R1
        LDR R6,=sc_ff_powers
        MOVS R7,#0
ff_more:
        CBZ R4,ff_done
        LSLS R0,R4,#31
        BPL ff_next
        MOV R0,R6
        MOV R1,R5
        CFI FunCall fast_gf2_apply
        BL fast_gf2_apply
        LDRH R1,[R6,#32]
        EOR R5,R0,R1
; Следующая степень соответствует следующему биту длины, после 14 снова степень 0.
ff_next:
        LSRS R4,R4,#1
        ADDS R6,R6,#36
        ADDS R7,R7,#1
        CMP R7,#15
        BNE ff_more
        LDR R6,=sc_ff_powers
        MOVS R7,#0
        B ff_more
ff_done:
        MOV R0,R5
        POP {R4-R8,PC}
          CFI EndBlock cfiBlock0
        LTORG

