// Хеш записи ID: два младших байта индекса и десять байт идентификатора.
// FNV-1a работает в uint32_t с естественным переполнением.
// Десять шагов развёрнуты: это измеренный быстрый вариант без цикла.
#include <stdint.h>

// Вычислить FNV-1a по точному 12-байтовому ключу индекса.
uint32_t idindex_hash(uint16_t index, const uint8_t *id)
{
  uint32_t h = (2166136261u ^ (uint8_t)index) * 16777619u;
  h = (h ^ (index >> 8)) * 16777619u;
  h = (h ^ id[0]) * 16777619u;
  h = (h ^ id[1]) * 16777619u;
  h = (h ^ id[2]) * 16777619u;
  h = (h ^ id[3]) * 16777619u;
  h = (h ^ id[4]) * 16777619u;
  h = (h ^ id[5]) * 16777619u;
  h = (h ^ id[6]) * 16777619u;
  h = (h ^ id[7]) * 16777619u;
  h = (h ^ id[8]) * 16777619u;
  h = (h ^ id[9]) * 16777619u;
  return h;
}
