// Независимый аппаратный сторож IWDG через регистры CMSIS.
// Предделитель 32 и прежний предел перезагрузки сохраняют время до сброса.
// При _DEBUGER сторож отключён, как в исходном приложении.

#include "wdt_stm32f10x.h"


// Инициализация таймера
// value — число тактов после предделителя; предел регистра RLR — 4095.
// Запустить аппаратный сторож с предделителем 32.
void wdt_init (Int32U value)
{
#ifndef _DEBUGER
  // разрешаем доступ к регистрам таймера
  IWDG->KR = 0x5555u;
  // устанавливаем предделитель
  IWDG->PR = 3u;
  // программируем значение регистра начала счёта/перезагрузки
  if (value > 4095) value = 4095;
  IWDG->RLR = value & 0xfffu;
  // запускаем
  IWDG->KR = 0xCCCCu;
#endif
}

// Перезагрузка регистра сторожевого таймера
// Обслужить аппаратный сторож, если отладка не запрещает его.
void wdt_reload (void)
{
#ifndef _DEBUGER
  IWDG->KR = 0xAAAAu;
#endif
}