// Независимый аппаратный сторож IWDG платы v5.
// Предделитель 32 и счётчик 3750 дают около 3 секунд при LSI 40 кГц.
// Главный цикл и SysTick обслуживают сторож; остановка обоих вызывает сброс.

#include "wdt_stm32f10x.h"

// Запустить сторож на прежние 3 секунды без переменной настройки.
void wdt_init(void)
{
  IWDG->KR = 0x5555u; // Открыть запись PR и RLR.
  IWDG->PR = 3u;
  IWDG->RLR = 3750u;
  IWDG->KR = 0xCCCCu; // Запустить независимый счётчик.
}

// Продлить срок до сброса при работающем приложении.
void wdt_reload(void)
{
  IWDG->KR = 0xAAAAu;
}
